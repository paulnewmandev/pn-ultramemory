  // A fibre is a curve that dips towards the centre of the brain, the way white matter runs
  // under the cortex, and fades from where it leaves to where it arrives so its direction shows.
  const SEG = 5;
  function curvePoint(a, b, t, out) {
    const mx = (POS[a * 3] + POS[b * 3]) * 0.5, my = (POS[a * 3 + 1] + POS[b * 3 + 1]) * 0.5, mz = (POS[a * 3 + 2] + POS[b * 3 + 2]) * 0.5;
    const cx = mx * 0.55, cy = my * 0.55 - 0.05, cz = mz * 0.55;
    const u = 1 - t;
    out[0] = u * u * POS[a * 3] + 2 * u * t * cx + t * t * POS[b * 3];
    out[1] = u * u * POS[a * 3 + 1] + 2 * u * t * cy + t * t * POS[b * 3 + 1];
    out[2] = u * u * POS[a * 3 + 2] + 2 * u * t * cz + t * t * POS[b * 3 + 2];
    return out;
  }
  const MAX_DRAWN_EDGES = 60000;
  const EDRAWN = Math.min(E, MAX_DRAWN_EDGES);
  const edgeData = new Float32Array(EDRAWN * SEG * 2 * LINE_STRIDE);
  const baseEdgeAlpha = Math.min(0.16, 0.045 * Math.sqrt(2000 / Math.max(1, EDRAWN)) + 0.01);
  const tmpA = [0, 0, 0], tmpB = [0, 0, 0];
  function writeCurve(arr, o, a, b, color, alpha, endFade) {
    for (let s = 0; s < SEG; s++) {
      const t0 = s / SEG, t1 = (s + 1) / SEG;
      curvePoint(a, b, t0, tmpA); curvePoint(a, b, t1, tmpB);
      arr[o] = tmpA[0]; arr[o + 1] = tmpA[1]; arr[o + 2] = tmpA[2];
      arr[o + 3] = color[0]; arr[o + 4] = color[1]; arr[o + 5] = color[2]; arr[o + 6] = alpha * (1 - endFade * t0);
      o += LINE_STRIDE;
      arr[o] = tmpB[0]; arr[o + 1] = tmpB[1]; arr[o + 2] = tmpB[2];
      arr[o + 3] = color[0]; arr[o + 4] = color[1]; arr[o + 5] = color[2]; arr[o + 6] = alpha * (1 - endFade * t1);
      o += LINE_STRIDE;
    }
    return o;
  }
