  // A position-based force layout: fibres pull, neighbours push apart, every particle stays
  // near its region and inside its part of the brain. It runs a few steps per frame, so the
  // brain is seen settling into shape rather than appearing after a pause.
  const SIM_STEPS = 150;
  let simStep = 0;
  const SPRING_W = new Float32Array(N);
  for (let i = 0; i < N; i++) SPRING_W[i] = 1 / Math.sqrt(1 + DEG[i]);
  function simulate(steps) {
    const cell = 0.055, inv = 1 / cell;
    for (let k = 0; k < steps && simStep < SIM_STEPS; k++, simStep++) {
      const heat = 1 - simStep / SIM_STEPS;
      for (let e = 0; e < E; e++) {
        const a = ESRC[e] * 3, b = EDST[e] * 3;
        if (HOME[ESRC[e]] !== HOME[EDST[e]]) continue;
        const dx = POS[b] - POS[a], dy = POS[b + 1] - POS[a + 1], dz = POS[b + 2] - POS[a + 2];
        const d = Math.sqrt(dx * dx + dy * dy + dz * dz) + 1e-6;
        const f = (d - 0.06) / d * 0.09 * heat * (REGION[ESRC[e]] === REGION[EDST[e]] ? 1 : 0.25);
        const wa = SPRING_W[ESRC[e]] * f, wb = SPRING_W[EDST[e]] * f;
        POS[a] += dx * wa; POS[a + 1] += dy * wa; POS[a + 2] += dz * wa;
        POS[b] -= dx * wb; POS[b + 1] -= dy * wb; POS[b + 2] -= dz * wb;
      }
      const grid = new Map();
      for (let i = 0; i < N; i++) {
        const o = i * 3;
        POS[o] += (HOME_ANCHOR[o] - POS[o]) * 0.035 * heat;
        POS[o + 1] += (HOME_ANCHOR[o + 1] - POS[o + 1]) * 0.035 * heat;
        POS[o + 2] += (HOME_ANCHOR[o + 2] - POS[o + 2]) * 0.035 * heat;
        const key = ((Math.floor(POS[o] * inv) + 64) * 128 + (Math.floor(POS[o + 1] * inv) + 64)) * 128 + (Math.floor(POS[o + 2] * inv) + 64);
        const bucket = grid.get(key);
        if (bucket) bucket.push(i); else grid.set(key, [i]);
      }
      for (let i = 0; i < N; i++) {
        const o = i * 3;
        const cx = Math.floor(POS[o] * inv), cy = Math.floor(POS[o + 1] * inv), cz = Math.floor(POS[o + 2] * inv);
        for (let gx = -1; gx <= 1; gx++) for (let gy = -1; gy <= 1; gy++) for (let gz = -1; gz <= 1; gz++) {
          const bucket = grid.get(((cx + gx + 64) * 128 + (cy + gy + 64)) * 128 + (cz + gz + 64));
          if (!bucket) continue;
          for (const j of bucket) {
            if (j <= i) continue;
            const p = j * 3;
            const dx = POS[p] - POS[o], dy = POS[p + 1] - POS[o + 1], dz = POS[p + 2] - POS[o + 2];
            const d2 = dx * dx + dy * dy + dz * dz;
            if (d2 >= cell * cell) continue;
            const d = Math.sqrt(d2) + 1e-6, push = (cell - d) / d * 0.25;
            POS[o] -= dx * push; POS[o + 1] -= dy * push; POS[o + 2] -= dz * push;
            POS[p] += dx * push; POS[p + 1] += dy * push; POS[p + 2] += dz * push;
          }
        }
      }
      for (let i = 0; i < N; i++) constrain(POS, i * 3, HOME[i]);
    }
    placeMemories();
  }

  // A memory floats just outside the cortex above the code it describes; one about code that is
  // not drawn joins a ring of loose thoughts over the crown.
  function placeMemories() {
    let loose = 0;
    const looseTotal = MEM.filter((m) => m.anchors.length === 0).length;
    MEM.forEach((m) => {
      if (m.anchors.length) {
        let x = 0, y = 0, z = 0;
        for (const a of m.anchors) { x += POS[a * 3]; y += POS[a * 3 + 1]; z += POS[a * 3 + 2]; }
        x /= m.anchors.length; y /= m.anchors.length; z /= m.anchors.length;
        const len = Math.hypot(x, y - 0.0, z) || 1;
        m.pos[0] = x + (x / len) * 0.13; m.pos[1] = y + (y / len) * 0.13 + 0.04; m.pos[2] = z + (z / len) * 0.13;
      } else {
        const t = (loose++ / Math.max(1, looseTotal)) * Math.PI * 2;
        m.pos[0] = Math.cos(t) * 0.55; m.pos[1] = 0.88; m.pos[2] = Math.sin(t) * 0.75;
      }
    });
  }

  // The cortex: points scattered over the surface, brighter on the folds, so the brain has its
  // outline even when the repository is small.
  function folds(x, y, z) {
    return (Math.sin(9 * z + 2.2 * Math.sin(6 * y)) + Math.sin(8.5 * y + 2.0 * Math.sin(7 * x + 1.3)) + 0.7 * Math.sin(11 * x + 3 * z + 1.7 * Math.sin(5 * y))) / 2.7;
  }
  function buildCortex() {
    const out = [];
    const r2 = rng(7);
    const unit = () => { const u = r2() * 2 - 1, t = r2() * Math.PI * 2, s = Math.sqrt(1 - u * u); return [s * Math.cos(t), u, s * Math.sin(t)]; };
    const COUNT = 11000;
    for (let n = 0; n < COUNT; n++) {
      const pick = r2();
      let x, y, z, bright;
      if (pick < 0.84) {
        const h = r2() < 0.5 ? -1 : 1;
        const d = unit();
        const ry = d[1] < 0 ? HEMI.ryb : HEMI.ry;
        x = h * HEMI.x + d[0] * HEMI.rx; y = HEMI.y + d[1] * ry; z = HEMI.z + d[2] * HEMI.rz;
        if (h * x < FISSURE * 0.6) continue;
        const g = folds(x, y, z);
        const sulcus = Math.abs(g) < 0.14;
        const k = sulcus ? 0.955 : 1.0 + 0.012 * g;
        x = h * HEMI.x + (x - h * HEMI.x) * k; y = HEMI.y + (y - HEMI.y) * k; z = HEMI.z + (z - HEMI.z) * k;
        bright = sulcus ? 0.18 : 0.30 + 0.45 * Math.abs(g);
      } else if (pick < 0.97) {
        const d = unit();
        x = CERE.x + d[0] * CERE.rx; y = CERE.y + d[1] * CERE.ry; z = CERE.z + d[2] * CERE.rz;
        const stripes = Math.abs(Math.sin(y * 70 + x * 4));
        bright = 0.18 + 0.4 * stripes;
      } else {
        const t = r2(), a = r2() * Math.PI * 2;
        x = Math.cos(a) * 0.085; z = -0.22 + Math.sin(a) * 0.085 - t * 0.12; y = -0.30 - t * 0.55;
        bright = 0.25;
      }
      out.push(x, y, z, bright);
    }
    return out;
  }

